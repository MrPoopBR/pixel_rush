def imagem_ameaca(code, phase=0):
    if code not in REFINADOS or os.environ.get('PIXELRUSH_ARTE_CLASSICA') == '1':
        return previous_image(code, phase)
    key = (code, int(phase) % 3)
    if key not in _CACHE:
        _, _, w, h, _ = AMEACAS[code]
        _CACHE[key] = pygame.transform.smoothscale(_paint(*key), (w, h)).convert_alpha()
    return _CACHE[key]


